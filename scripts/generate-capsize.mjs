/**
 * Generates renderer-react/src/styles/capsize.generated.css
 *
 * Run: node scripts/generate-capsize.mjs  (or `pnpm capsize`)
 *
 * Uses the actual Archivo Regular metrics to produce Capsize-trimmed
 * utility classes for every font size in the design token scale. Each class
 * kills the intrinsic whitespace above the cap-height and below the baseline
 * that the font bakes in — no more mystery gaps inside components.
 *
 * Classes are px-suffixed to avoid collisions with Tailwind's t-shirt sizes
 * (text-xs is 12px but the old cap-xs was 14px — a silent footgun). A cap-N
 * class replaces the Tailwind text-* utility on that element: it sets both the
 * font-size and the trimmed line-height.
 *
 *   small/in-use tier : cap-9 cap-10 cap-11 cap-12 cap-14 cap-15 cap-18
 *   editorial headings : cap-20 cap-23 cap-28 cap-35 cap-40
 */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createStyleObject, createStyleString } from '@capsizecss/core';
import { fromFile } from '@capsizecss/unpack/fs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const fontPath = resolve(__dirname, '../renderer-react/src/assets/fonts/Archivo-Regular.ttf');
const outPath = resolve(__dirname, '../renderer-react/src/styles/capsize.generated.css');

const metrics = await fromFile(fontPath);

// Hybrid type scale → { className-suffix, fontSize px, leading px }.
// Reconciled against what the renderer actually uses (see DESIGN.md Typography):
//   - small/in-use tier carries the app's CURRENT line-heights, so swapping
//     text-* → cap-* only ADDS the Capsize trim (no rhythm change).
//   - 16px and 24px are intentionally absent: DESIGN.md bans 16px body text and
//     the scale has no 24px step — text-base folds to cap-15/cap-18 and
//     text-2xl(24) to cap-23 during the retrofit.
//   - editorial heading steps (20/23/28/35/40) use leading = px × 1.5 (even).
const sizes = [
  { name: '9', px: 9, leading: 12 }, // text-micro  · count/overflow badges
  { name: '10', px: 10, leading: 14 }, // text-3xs   · metadata chips, dense cells
  { name: '11', px: 11, leading: 15 }, // text-2xs   · secondary labels, captions
  { name: '12', px: 12, leading: 16 }, // text-xs    · Tailwind default
  { name: '14', px: 14, leading: 20 }, // text-sm    · Tailwind default (most used)
  { name: '15', px: 15, leading: 22 }, // body-sm    · fold target for stray 16px
  { name: '18', px: 18, leading: 28 }, // text-lg    · body / Tailwind default
  { name: '20', px: 20, leading: 30 }, // title-xs
  { name: '23', px: 23, leading: 34 }, // title-sm   · fold target for text-2xl(24)
  { name: '28', px: 28, leading: 42 }, // title-md
  { name: '35', px: 35, leading: 52 }, // title-lg
  { name: '40', px: 40, leading: 60 }, // title-xl

  // Prose variants — same Capsize trim, but a comfortable ~1.6 leading for
  // multi-line body copy (asset descriptions, privacy text, notes) where the
  // tight UI leading above would cramp reading. Use cap-N-prose on paragraphs.
  { name: '10-prose', px: 10, leading: 16 },
  { name: '11-prose', px: 11, leading: 18 },
  { name: '12-prose', px: 12, leading: 20 },
];

const lines = [
  '/* ============================================================',
  ' * capsize.generated.css — DO NOT EDIT',
  ' * Generated by scripts/generate-capsize.mjs',
  ' * Font: Archivo Regular',
  ' * Re-run the script whenever you change the font or type scale.',
  ' * ============================================================ */',
  '',
  '/*',
  ` * Font metrics: capHeight=${metrics.capHeight} ascent=${metrics.ascent}`,
  ` * descent=${metrics.descent} lineGap=${metrics.lineGap} unitsPerEm=${metrics.unitsPerEm}`,
  ' *',
  ' * THESE TRIMS ARE FOUNDERS GROTESK ONLY. The negative margins below are',
  ' * derived from the metrics above, so a cap-N class on a `font-mono` element',
  ' * trims by the wrong amount. With `truncate` (overflow: hidden) in the mix',
  ' * that is not cosmetic: cap-10 collapsed JetBrains Mono to a 6px box around',
  ' * 12px of text, and every scan-location path in Settings rendered with its',
  ' * bottom half cut off. Mono text that clips wants an explicit',
  ' * `text-[Npx] leading-[Npx]` until a mono-metric set exists here.',
  ' */',
  '',
];

for (const { name, px, leading } of sizes) {
  const css = createStyleString(`cap-${name}`, {
    fontSize: px,
    leading,
    fontMetrics: metrics,
  });
  lines.push(css.trim(), '');
}

// Capsize trims the line box to exactly cap-height..baseline, which puts
// descenders (and diacritics) OUTSIDE the element's box. That is harmless while
// overflow is visible — and destructive the moment anything clips. `truncate`
// and `line-clamp-*` both set `overflow: hidden`, so a trimmed element wearing
// either renders with its bottom sliced off: `truncate cap-14` measured a 9px
// box around 17px of text, which is how every scan-location path and asset-card
// title in the app lost its descenders.
//
// The two features are simply incompatible, so the trim yields. `content: none`
// stops the pseudo-element being generated at all, which takes its negative
// margins with it and restores the normal line box. This lives here rather than
// in global.css because it must win the cascade against the rules above, and
// this file is imported last.
lines.push('/* Clipping and Capsize are incompatible — see the note in the generator. */');
lines.push(
  [
    '.truncate::before,',
    '.truncate::after,',
    '[class*="line-clamp-"]::before,',
    '[class*="line-clamp-"]::after {',
    '  content: none;',
    '}',
  ].join('\n'),
);
lines.push('');

// Also emit a CSS custom property set for the trim offsets at body size (18px/27px)
// so components can reference them directly without a class.
const bodyObj = createStyleObject({
  fontSize: 18,
  leading: 27,
  fontMetrics: metrics,
});
lines.push('/* Body-size trim offsets as custom properties */');
lines.push(':root {');
lines.push(`  --cap-before-margin: ${bodyObj['::before'].marginBottom};`);
lines.push(`  --cap-after-margin: ${bodyObj['::after'].marginTop};`);
lines.push('}');
lines.push('');

writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`✓ Written ${outPath}`);
console.log(`  Font: ${metrics.familyName}`);
console.log(`  capHeight: ${metrics.capHeight} / ${metrics.unitsPerEm} units per em`);
